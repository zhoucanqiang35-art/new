import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { writeFile } from 'node:fs/promises';

const execFileAsync = promisify(execFile);
const origin = 'https://findspreadsheet.com';
const categories = ['shoes', 'hoodies-sweaters', 't-shirts', 'jackets', 'pants-shorts', 'headwear', 'accessories', 'jersey', 'ShortSets', 'electronics', 'other-stuff'];
const MAX_PAGES_PER_CATEGORY = 500;
const delay = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));

function cleanText(value = '') {
  return String(value).replace(/<[^>]*>/g, ' ').replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/\s+/g, ' ').trim();
}

function sourceUrl(path) {
  const url = new URL(path, origin);
  if (url.origin !== origin) return null;
  return url;
}

async function sourceHtml(path) {
  const url = sourceUrl(path);
  if (!url) return '';
  // This is a one-time, respectful catalogue export.  Keep requests serial
  // and paced instead of running thousands of concurrent product fetches.
  await delay(450);
  const { stdout } = await execFileAsync('curl', ['-fsSL', '--retry', '3', '--retry-delay', '2', '--connect-timeout', '10', '--max-time', '35', '-A', 'PikoBuySpreadsheetCatalogSync/1.0', url.href], { maxBuffer: 12 * 1024 * 1024 });
  return stdout;
}

function categoryPages(html, slug) {
  const block = (String(html).match(/<div class="pagination">([\s\S]*?)<\/div>/i) || [])[1] || '';
  const allowed = new RegExp(`^/${slug.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}/(?:list_\\d+_\\d+/)?$`, 'i');
  const pages = new Set();
  for (const hit of block.matchAll(/href="([^"]+)"/gi)) {
    const url = sourceUrl(hit[1]);
    if (url && allowed.test(url.pathname)) pages.add(url.pathname + url.search);
  }
  return [...pages];
}

function parseProducts(html) {
  const purchaseIds = new Map();
  for (const purchase of String(html).matchAll(/data-cart-url="([^"]+)"[\s\S]{0,800}?data-cart-weidian="(\d{5,})"/gi)) {
    const path = sourceUrl(purchase[1])?.pathname;
    if (path) purchaseIds.set(path, purchase[2]);
  }
  const products = [];
  const matcher = /<div class="product-card[\s\S]*?data-id="([^"]+)"[\s\S]*?<a href="([^"]+)" class="product-image">[\s\S]*?data-src="([^"]+)" alt="([^"]*)"[\s\S]*?<h3 class="product-name">([\s\S]*?)<\/h3>[\s\S]*?<div class="product-price">([^<]+)/gi;
  for (const hit of html.matchAll(matcher)) {
    const [id, path, image, alt, title, price] = hit.slice(1);
    const page = sourceUrl(path);
    if (!page || !/^\/[^/]+\/.+-\d+\.html$/i.test(page.pathname)) continue;
    products.push({ id, path: page.pathname, image: new URL(image, origin).href, alt: cleanText(alt), title: cleanText(title), price: cleanText(price), weidian: purchaseIds.get(page.pathname) || '' });
  }
  return products;
}

async function crawlCategory(slug) {
  const first = `/${slug}/`;
  const queue = [first];
  const seen = new Set();
  const products = new Map();
  while (queue.length) {
    const path = queue.shift();
    if (seen.has(path)) continue;
    if (seen.size >= MAX_PAGES_PER_CATEGORY) throw new Error(`${slug}: reached ${MAX_PAGES_PER_CATEGORY} pages; refusing to write a partial snapshot`);
    seen.add(path);
    const html = await sourceHtml(path);
    for (const product of parseProducts(html)) products.set(product.path, product);
    for (const next of categoryPages(html, slug)) if (!seen.has(next)) queue.push(next);
  }
  console.log(`${slug}: ${seen.size} source pages, ${products.size} products`);
  return [...products.values()];
}

const groups = [];
for (const category of categories) groups.push(await crawlCategory(category));
const byPath = new Map();
for (const product of groups.flat()) byPath.set(product.path, product);
const snapshot = [...byPath.values()];
if (!snapshot.length) throw new Error('No products were parsed; snapshot was not written.');
await writeFile(new URL('../worker/catalog-data.js', import.meta.url), `// Generated by recursively crawling every public category page on FindSpreadsheet.\nconst SNAPSHOT_PRODUCTS = ${JSON.stringify(snapshot)};\n\n`, 'utf8');
console.log(`Wrote ${snapshot.length} products from ${categories.length} complete category crawls.`);
