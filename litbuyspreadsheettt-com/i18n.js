  function dict(l) {
    const d = {};
    if (packs[l]) K.forEach((k, i) => (d[k] = packs[l][i]));
    return Object.assign(d, extra[l] || {});
  }
  const pageTitle = document.title;
  function apply(l) {
    const d = dict(l);
    document.documentElement.lang = l;
    document.querySelectorAll("[data-i18n]").forEach((e) => {
      const k = e.dataset.i18n;
      e.textContent = d[k] || k;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((e) => {
      const k = e.dataset.i18nPlaceholder;
      e.placeholder = d[k] || k;
    });
    const s = document.querySelector(".language-switch select");
    if (s) s.value = l;
    document.title =
      l === "en" ? pageTitle : "LitBuy Spreadsheet | " + locale[l];
    window.dispatchEvent(
      new CustomEvent("litbuy-language", { detail: { lang: l } }),
    );
  }
  function init() {
    document.querySelectorAll(".language-switch").forEach((w) => {
      w.innerHTML =
        '<select aria-label="Language">' +
        Object.entries(locale)
          .map(([k, v]) => '<option value="' + k + '">' + v + "</option>")
          .join("") +
        "</select>";
      const s = w.querySelector("select");
      s.addEventListener("change", () => {
        sessionStorage.setItem("litbuy-language", s.value);
        apply(s.value);
      });
    });
    const saved = (sessionStorage.getItem("litbuy-language") || "").trim().toLowerCase();
    const supported = ["en", "de", "fr", "es", "it", "pt", "nl", "pl", "ru"];
    const initialLanguage = supported.includes(saved) ? saved : "en";
    if (saved !== initialLanguage) sessionStorage.setItem("litbuy-language", initialLanguage);
    apply(initialLanguage);
  }
  document.readyState === "loading"
    ? document.addEventListener("DOMContentLoaded", init)
    : init();
